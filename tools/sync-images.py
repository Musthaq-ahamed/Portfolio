#!/usr/bin/env python3
"""
Scan the photo folders and write js/gallery.js, which the site reads automatically.

  assets/projects/<project-id>/   photos for that project (card cover + popup gallery)
  assets/malaysia/                photos from the Malaysia trip (Top Moments section)

Rules
  * A file named cover.jpg / cover.png / cover.webp becomes the card image; otherwise the first photo is used.
  * Photos show in filename order (01-..., 02-... if you care about order).
  * jpg / jpeg / png / webp / gif / avif are picked up.

Usage
  python3 tools/sync-images.py              # just rebuild js/gallery.js
  python3 tools/sync-images.py --optimize   # also shrink big photos (needs:  pip install pillow)
                                            # longest side -> 1800px, JPEG quality 82 (originals are overwritten, so keep a copy)
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXT = ('.jpg', '.jpeg', '.png', '.webp', '.gif', '.avif')
OPTIMIZE = '--optimize' in sys.argv

def natural(s):
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r'(\d+)', s)]

def optimize(path):
    try:
        from PIL import Image, ImageOps
    except ImportError:
        sys.exit('--optimize needs Pillow:  pip install pillow')
    ext = os.path.splitext(path)[1].lower()
    if ext in ('.gif', '.avif'):
        return
    im = ImageOps.exif_transpose(Image.open(path))
    if max(im.size) > 1800:
        im.thumbnail((1800, 1800))
    if ext in ('.jpg', '.jpeg'):
        im.convert('RGB').save(path, quality=82, optimize=True, progressive=True)
    elif ext == '.webp':
        im.save(path, quality=82, method=6)
    else:
        im.save(path, optimize=True)

def scan(folder):
    full = os.path.join(ROOT, folder)
    if not os.path.isdir(full):
        return []
    files = sorted((f for f in os.listdir(full) if f.lower().endswith(EXT) and not f.startswith('.')), key=natural)
    files.sort(key=lambda f: 0 if os.path.splitext(f)[0].lower() == 'cover' else 1)   # cover first (stable)
    out = []
    for f in files:
        p = os.path.join(full, f)
        if OPTIMIZE:
            optimize(p)
        out.append(folder.replace(os.sep, '/') + '/' + f)
    return out

projects = {}
base = os.path.join(ROOT, 'assets', 'projects')
if os.path.isdir(base):
    for pid in sorted(os.listdir(base)):
        if os.path.isdir(os.path.join(base, pid)):
            imgs = scan(f'assets/projects/{pid}')
            if imgs:
                projects[pid] = imgs
gallery = {'projects': projects, 'malaysia': scan('assets/malaysia')}

with open(os.path.join(ROOT, 'js', 'gallery.js'), 'w') as fh:
    fh.write('/* Generated by tools/sync-images.py — do not edit by hand. */\nwindow.GALLERY = ' + json.dumps(gallery, indent=2) + ';\n')

print('Projects with photos:', ', '.join(f'{k} ({len(v)})' for k, v in projects.items()) or 'none yet')
print('Malaysia photos:', len(gallery['malaysia']))
